#!/usr/bin/env node
// Generate the browser copy from the two published artifact schemas.
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const schemas = {};
const supported = new Set(['$schema', '$id', '$defs', '$ref', 'title', 'type', 'additionalProperties', 'required', 'properties', 'const', 'enum', 'format', 'items', 'minLength', 'minimum']);
function check(schema) {
  if (typeof schema === 'boolean') return;
  for (const key of Object.keys(schema)) if (!supported.has(key)) throw new Error('Unsupported runtime schema keyword: ' + key);
  if (schema.$ref && !schema.$ref.startsWith('#/$defs/')) throw new Error('Only local definition references are supported');
  if (schema.format && !['date', 'date-time'].includes(schema.format)) throw new Error('Unsupported format: ' + schema.format);
  for (const key of ['$defs', 'properties']) for (const value of Object.values(schema[key] || {})) check(value);
  for (const key of ['items', 'additionalProperties']) if (schema[key] && typeof schema[key] === 'object') check(schema[key]);
}
for (const [key, file] of Object.entries({ result: 'audit-result', baseline: 'audit-baseline' })) {
  schemas[key] = JSON.parse(await fs.readFile(new URL('schemas/' + file + '.schema.json', root), 'utf8'));
  check(schemas[key]);
}
const output = '// Generated by scripts/sync-artifact-schemas.mjs. Edit schemas/, then regenerate.\n(function () {\n  "use strict";\n  const schemas = ' + JSON.stringify(schemas) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = schemas;\n  if (typeof globalThis !== "undefined") globalThis.FrontendArtifactSchemas = schemas;\n})();\n';
const target = new URL('analysis/artifact-schemas.js', root);
if (process.argv.includes('--check')) {
  if (await fs.readFile(target, 'utf8').catch(() => '') !== output) throw new Error('Artifact schemas are out of sync: run node scripts/sync-artifact-schemas.mjs');
  process.stdout.write('Artifact schema browser copy is synchronized.\n');
} else {
  await fs.writeFile(target, output);
  process.stdout.write('Generated ' + fileURLToPath(target) + '\n');
}
